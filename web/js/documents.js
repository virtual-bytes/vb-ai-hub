// ---------- document viewer
const doc = { versions: [], cur: null, raw: false, text: "" };
async function openDoc(owner, path) {
  let atts;
  if (state.archive && state.archive.owner === owner) atts = state.archive.attachments;
  else atts = (await api(`/api/owners/${enc(owner)}/archive`)).attachments;
  doc.versions = atts.filter(a => a.path === path).sort((a, b) => b.created_at - a.created_at);
  if (!doc.versions.length) return toast("Document not found");
  doc.raw = false;
  $("#docVersion").innerHTML = doc.versions.map((v, i) => `<option value="${i}">${i === 0 ? "Latest · " : ""}${esc(fullDate(v.created_at))} · ${size(v.size)}</option>`).join("");
  $("#docVersion").hidden = doc.versions.length < 2;
  $("#docDlg").showModal(); await showVersion(0);
}
async function showVersion(i) {
  const v = doc.versions[i]; doc.cur = v;
  $("#docTitle").textContent = v.name; $("#docPath").textContent = v.path.startsWith("generated:") ? "Generated by the hub" : v.path !== v.name ? v.path : "";
  const body = $("#docBody");
  const text = /^(text\/|application\/(json|yaml|x-yaml|xml|toml))/.test(v.mime) || /\.(md|markdown|txt|rst|adoc|ya?ml|json|toml|sh|py|tf|hcl|ini)$/i.test(v.name);
  $("#docRaw").hidden = !/\.(md|markdown)$/i.test(v.name);
  if (!text) { body.innerHTML = `<div class="notice">Preview isn't available for this file type (${esc(v.mime)}, ${size(v.size)}). Use Download.</div>`; return; }
  body.innerHTML = `<div class="sub">Loading…</div>`;
  try { doc.text = await (await fetchBlob(`/api/blobs/${v.sha}`)).text(); } catch (e) { body.innerHTML = `<div class="notice">${esc(e.message)}</div>`; return; }
  renderDocBody();
}
function renderDocBody() {
  const isMd = /\.(md|markdown)$/i.test(doc.cur.name) && !doc.raw;
  $("#docBody").innerHTML = isMd ? `<div class="md">${md(doc.text)}</div>` : `<pre class="plain">${esc(doc.text)}</pre>`;
  $("#docRaw").textContent = doc.raw ? "Formatted" : "Raw";
}
$("#docVersion").onchange = e => showVersion(+e.target.value);
$("#docRaw").onclick = () => { doc.raw = !doc.raw; renderDocBody(); };
$("#docDownload").onclick = () => download(`/api/blobs/${doc.cur.sha}`, doc.cur.name);
$("#docClose").onclick = () => $("#docDlg").close();
